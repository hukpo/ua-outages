/**
 * Builds the digit templates (src/image/digit-templates.ts) the poster reader matches against,
 * from labelled posters in test/fixtures/chernihiv/posters (labels.json: file → date and the
 * times on each card). Rerun after adding posters, e.g. when the operator changes its font.
 *
 *   npx tsx scripts/train-digits.ts           rebuild the templates
 *   npx tsx scripts/train-digits.ts --check   read every labelled poster and compare
 *   npx tsx scripts/train-digits.ts --dump a.jpg …   print what the reader sees, for labelling
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { posterDateGlyphs, posterTimeGlyphs, readCardPoster } from '../src/image/cards.js'
import { glyphVector, type Box, type Mask } from '../src/image/glyphs.js'
import { decodeJpeg } from '../src/image/jpeg.js'
import { encodeModel, trainModel } from '../src/image/template-codec.js'
import { CHERNIHIV_POSTER } from '../src/providers/chernihiv.js'

const DIR = 'test/fixtures/chernihiv/posters'
type Labels = Record<string, { date: string; cards: string[] }>
const labels = JSON.parse(readFileSync(join(DIR, 'labels.json'), 'utf8')) as Labels
const fmt = (m: number) => `${String(Math.floor(m / 60)).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}`
const cardText = (slots: { start: number; end: number }[]) =>
  slots.map((s) => `${fmt(s.start)}-${s.end === 1440 ? '00:00' : fmt(s.end)}`).join(' ')

const args = process.argv.slice(2)
if (args[0] === '--dump') {
  for (const f of args.slice(1)) {
    try {
      const p = readCardPoster(decodeJpeg(readFileSync(f)), CHERNIHIV_POSTER)
      console.log(JSON.stringify({ [f]: { date: p.date, cards: p.cards.map(cardText) } }))
    } catch (e) {
      console.log(f, 'ERROR', (e as Error).message)
    }
  }
} else if (args[0] === '--check') {
  let bad = 0
  for (const [file, want] of Object.entries(labels)) {
    try {
      const p = readCardPoster(decodeJpeg(readFileSync(join(DIR, file))), CHERNIHIV_POSTER)
      const got = p.cards.map(cardText)
      const diffs = got.flatMap((g, i) =>
        g === want.cards[i] ? [] : [`card ${i + 1}: ${g} ≠ ${want.cards[i]}`],
      )
      if (p.date !== want.date) diffs.push(`date ${p.date} ≠ ${want.date}`)
      if (diffs.length) bad++
      console.log(diffs.length ? '✗' : '✓', file, diffs.join('; '))
    } catch (e) {
      bad++
      console.log('✗', file, (e as Error).message)
    }
  }
  process.exitCode = bad ? 1 : 0
} else {
  const samples: Parameters<typeof trainModel>[0] = []
  const add = (mask: Mask, box: Box, digit: string) =>
    samples.push({ digit, vector: glyphVector(mask, box), aspect: (box.x1 - box.x0) / (box.y1 - box.y0) })
  for (const [file, want] of Object.entries(labels)) {
    const img = decodeJpeg(readFileSync(join(DIR, file)))
    posterTimeGlyphs(img, CHERNIHIV_POSTER).forEach(({ mask, lines }, i) => {
      const times = want.cards[i]!.split(' ').filter(Boolean)
      if (times.length !== lines.length)
        throw new Error(`${file} card ${i + 1}: ${lines.length} time lines, label has ${times.length}`)
      lines.forEach((boxes, j) => {
        const digits = times[j]!.replace(/\D/g, '')
        if (boxes.length !== digits.length)
          throw new Error(`${file} card ${i + 1} line ${j + 1}: ${boxes.length} digit glyphs`)
        boxes.forEach((box, k) => add(mask, box, digits[k]!))
      })
    })
    // the header date is often in another weight of the font; it trains the same model
    const dates = posterDateGlyphs(img, CHERNIHIV_POSTER)
    if (dates.length !== 1) throw new Error(`${file}: found ${dates.length} header dates`)
    const [y, mo, d] = want.date.split('-')
    const digits = `${d}${mo}${y}`.slice(-dates[0]!.boxes.length) // "1.11.2026" has one day digit
    dates[0]!.boxes.forEach((box, k) => add(dates[0]!.mask, box, digits[k]!))
  }
  const model = trainModel(samples)
  const counts = Object.keys(model.digits).map((d) => `${d}×${samples.filter((s) => s.digit === d).length}`)
  const missing = '0123456789'.split('').filter((d) => !model.digits[d])
  console.log(counts.join(' '), missing.length ? `MISSING ${missing.join(',')}` : '')
  writeFileSync(
    'src/image/digit-model.ts',
    `// Generated by scripts/train-digits.ts from the posters in ${DIR} — do not edit by hand.\n` +
      `import { decodeModel } from './template-codec.js'\n\n` +
      `export const DIGIT_MODEL = decodeModel(${JSON.stringify(encodeModel(model), null, 2)})\n`,
  )
}
